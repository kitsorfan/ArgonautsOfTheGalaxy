// Bundles the three.js game into a single self-contained HTML page.
//
//   node game/build.mjs          one-off build
//   node game/build.mjs --watch  rebuild on change
//
// Outputs:
//   game/dist/index.html          open in a browser to play on desktop
//   src/generated/gameHtml.ts     the same page as a string, loaded by the app's WebView
//   game/dist/music, public/music the soundtrack (assets/music), next to the page for browsers; the app
//                                 bundles assets/music itself and plays it natively (src/music.ts)
import { context, build } from 'esbuild';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const watch = process.argv.includes('--watch');

const FONTS = [
  ['Fredoka', 500, 'fredoka/500Medium/Fredoka_500Medium.ttf'],
  ['Fredoka', 600, 'fredoka/600SemiBold/Fredoka_600SemiBold.ttf'],
  ['Fredoka', 700, 'fredoka/700Bold/Fredoka_700Bold.ttf'],
  ['Orbitron', 700, 'orbitron/700Bold/Orbitron_700Bold.ttf'],
  ['Orbitron', 800, 'orbitron/800ExtraBold/Orbitron_800ExtraBold.ttf'],
];

/**
 * Fredoka and Orbitron have no Greek letters. These faces fill in just the Greek glyphs under the same
 * family names (the browser picks them by `unicode-range`), so the CSS never has to change: a rounded
 * face that matches Fredoka, and a techy one for Orbitron's headings.
 */
const GREEK_FONTS = [
  ['Fredoka', 500, 'm-plus-rounded-1c/500Medium/MPLUSRounded1c_500Medium.ttf'],
  ['Fredoka', 600, 'm-plus-rounded-1c/700Bold/MPLUSRounded1c_700Bold.ttf'],
  ['Fredoka', 700, 'm-plus-rounded-1c/800ExtraBold/MPLUSRounded1c_800ExtraBold.ttf'],
  ['Orbitron', 700, 'play/700Bold/Play_700Bold.ttf'],
  ['Orbitron', 800, 'play/700Bold/Play_700Bold.ttf'],
];
const GREEK_RANGE = 'U+0370-03FF,U+1F00-1FFF';
const GREEK_TEXT = (() => {
  let s = '';
  for (const [a, b] of [
    [0x370, 0x3ff],
    [0x1f00, 0x1fff],
  ]) {
    for (let c = a; c <= b; c++) s += String.fromCodePoint(c);
  }
  return s;
})();

const fontFile = (file) => readFileSync(join(root, 'node_modules/@expo-google-fonts', file));

async function fontFaces() {
  const faces = FONTS.map(([family, weight, file]) => {
    const data = fontFile(file).toString('base64');
    return `@font-face{font-family:'${family}';font-weight:${weight};font-style:normal;font-display:block;src:url(data:font/ttf;base64,${data}) format('truetype')}`;
  });
  // Declared after the Latin faces, so they win for the characters in their range.
  for (const [family, weight, file] of GREEK_FONTS) {
    const data = (await subsetFont(fontFile(file), GREEK_TEXT, { targetFormat: 'woff2' })).toString('base64');
    faces.push(`@font-face{font-family:'${family}';font-weight:${weight};font-style:normal;font-display:block;unicode-range:${GREEK_RANGE};src:url(data:font/woff2;base64,${data}) format('woff2')}`);
  }
  return faces.join('\n');
}

const FONT_CSS = await fontFaces();

function page(js) {
  const css = readFileSync(join(here, 'src/ui/style.css'), 'utf8');
  const safeJs = js.replace(/<\/script/gi, '<\\/script');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<meta name="theme-color" content="#03040a">
<title>Argonauts of the Galaxy</title>
<style>
${FONT_CSS}
${css}
</style>
</head>
<body>
<canvas id="game"></canvas>
<div id="vignette"></div>
<div id="touch"></div>
<div id="ui"></div>
<script>
${safeJs}
</script>
</body>
</html>
`;
}

/** Copies the soundtrack next to the browser page (game/dist) and into Expo web's public folder, skipping unchanged files. */
function copyMusic() {
  const src = join(root, 'assets/music');
  for (const dir of [join(here, 'dist/music'), join(root, 'public/music')]) {
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(src).filter((f) => f.endsWith('.mp3'))) {
      const to = join(dir, f);
      if (existsSync(to) && statSync(to).size === statSync(join(src, f)).size) continue;
      copyFileSync(join(src, f), to);
    }
  }
}

function emit(js) {
  const html = page(js);
  mkdirSync(join(here, 'dist'), { recursive: true });
  writeFileSync(join(here, 'dist/index.html'), html);
  mkdirSync(join(root, 'src/generated'), { recursive: true });
  writeFileSync(
    join(root, 'src/generated/gameHtml.ts'),
    `// Generated by game/build.mjs. Do not edit: run \`npm run game:build\`.\nconst html: string = ${JSON.stringify(html)};\nexport default html;\n`,
  );
  copyMusic();
  console.log(`game: wrote ${(html.length / 1024).toFixed(0)} KB`);
}

const options = {
  entryPoints: [join(here, 'src/main.ts')],
  bundle: true,
  format: 'iife',
  target: ['es2020', 'chrome90', 'safari15'],
  minify: !watch,
  sourcemap: false,
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [
    {
      name: 'emit-html',
      setup(b) {
        b.onEnd((result) => {
          if (result.errors.length || !result.outputFiles?.length) return;
          emit(result.outputFiles[0].text);
        });
      },
    },
  ],
};

if (watch) {
  const ctx = await context(options);
  await ctx.watch();
  console.log('game: watching for changes...');
} else {
  await build(options);
}
